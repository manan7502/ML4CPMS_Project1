#!/usr/bin/env python3
"""
MAIN115 — STRICT CROSS-FITTED SPECIALIST CONSENSUS CORRECTION

Goal:
    Test whether several independently trained specialists can safely correct
    a small number of Main64 teacher predictions.

Important:
    - Uses Main114's saved 62-D feature matrix.
    - Specialist predictions on the 8428 OOF rows are generated by 5-fold
      cross-fitting, so the specialist itself never predicts a row it trained on.
    - The correction rule is selected using only the cross-fitted OOF predictions.
    - The selected rule is frozen and applied once to the 2108 validation rows.
    - No Kaggle submission is produced.

This is deliberately conservative: we only override Main64 when multiple
specialists independently disagree with it with sufficient confidence.
"""

import json
import warnings
from pathlib import Path

import numpy as np
from sklearn.base import clone
from sklearn.ensemble import ExtraTreesClassifier, HistGradientBoostingClassifier, RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, roc_auc_score
from sklearn.model_selection import StratifiedKFold

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "corrected_main114_results.npz"
OUT_REPORT = ROOT / "main115_report.json"
OUT_NPZ = ROOT / "main115_results.npz"

N_SPLITS = 5
SEED = 115

print("=" * 78)
print("MAIN115 — STRICT CROSS-FITTED SPECIALIST CONSENSUS CORRECTION")
print("=" * 78)

z = np.load(RESULTS, allow_pickle=True)

X_oof = z["feature_oof"].astype(np.float32)
X_val = z["feature_val"].astype(np.float32)
y_oof = z["y_train"].astype(int)
y_val = z["y_val"].astype(int)
teacher_oof = z["teacher_oof"].astype(int)
teacher_val = z["teacher_val"].astype(int)

print(f"OOF features: {X_oof.shape}")
print(f"VAL features: {X_val.shape}")
print(f"Main64 OOF teacher: {accuracy_score(y_oof, teacher_oof):.9f}")
print(f"Main64 VAL teacher: {accuracy_score(y_val, teacher_val):.9f}")

# -------------------------------------------------------------------------
# Specialists.
#
# They are intentionally somewhat different:
#   LR        -> smooth linear boundary
#   HGBsmall -> shallow nonlinear interactions
#   HGBmedium-> stronger nonlinear model
#   RF        -> randomized tree ensemble
#   ExtraTrees-> highly randomized tree ensemble
#
# All are trained only on the 62-D Main114 feature representation.
# -------------------------------------------------------------------------
models = {
    "LR_C1": LogisticRegression(
        C=1.0, class_weight="balanced", max_iter=5000, solver="lbfgs"
    ),
    "HGB_small": HistGradientBoostingClassifier(
        learning_rate=0.06,
        max_iter=180,
        max_leaf_nodes=15,
        min_samples_leaf=20,
        l2_regularization=1.5,
        random_state=SEED,
    ),
    "HGB_medium": HistGradientBoostingClassifier(
        learning_rate=0.06,
        max_iter=260,
        max_leaf_nodes=31,
        min_samples_leaf=15,
        l2_regularization=1.0,
        random_state=SEED + 1,
    ),
    "RandomForest": RandomForestClassifier(
        n_estimators=500,
        max_depth=10,
        min_samples_leaf=5,
        max_features="sqrt",
        class_weight="balanced_subsample",
        n_jobs=-1,
        random_state=SEED + 2,
    ),
    "ExtraTrees": ExtraTreesClassifier(
        n_estimators=500,
        max_depth=12,
        min_samples_leaf=4,
        max_features="sqrt",
        class_weight="balanced",
        n_jobs=-1,
        random_state=SEED + 3,
    ),
}

names = list(models)
M = len(names)

skf = StratifiedKFold(N_SPLITS, shuffle=True, random_state=SEED)

# Honest cross-fitted probabilities for the OOF rows.
p_oof = np.zeros((len(y_oof), M), dtype=np.float64)

print("\n--- 5-fold cross-fitting specialists on Main64 OOF rows ---")

for fold, (tr, te) in enumerate(skf.split(X_oof, y_oof), 1):
    print(f"Fold {fold}/{N_SPLITS}: train={len(tr)} test={len(te)}")
    for j, name in enumerate(names):
        mdl = clone(models[name])
        mdl.fit(X_oof[tr], y_oof[tr])
        p_oof[te, j] = mdl.predict_proba(X_oof[te])[:, 1]

# Fit each specialist on all OOF rows and predict the held-out validation set.
p_val = np.zeros((len(y_val), M), dtype=np.float64)

print("\n--- Full specialist fit -> validation ---")
for j, name in enumerate(names):
    mdl = clone(models[name])
    mdl.fit(X_oof, y_oof)
    p_val[:, j] = mdl.predict_proba(X_val)[:, 1]

# -------------------------------------------------------------------------
# Diagnostics
# -------------------------------------------------------------------------
print("\n--- Specialist diagnostics ---")
diag = {}

for j, name in enumerate(names):
    pred_o = (p_oof[:, j] >= 0.5).astype(int)
    pred_v = (p_val[:, j] >= 0.5).astype(int)
    ao = accuracy_score(y_oof, pred_o)
    av = accuracy_score(y_val, pred_v)
    auc_o = roc_auc_score(y_oof, p_oof[:, j])
    auc_v = roc_auc_score(y_val, p_val[:, j])
    diag[name] = {
        "oof_accuracy": float(ao),
        "oof_auc": float(auc_o),
        "val_accuracy": float(av),
        "val_auc": float(auc_v),
    }
    print(
        f"{name:13s} OOF acc={ao:.6f} AUC={auc_o:.6f} | "
        f"VAL acc={av:.6f} AUC={auc_v:.6f}"
    )

# -------------------------------------------------------------------------
# Consensus representation.
#
# margin_j is signed toward the specialist's predicted class:
#   +1 approximately means strong B
#   -1 approximately means strong A
#
# For a teacher correction, orient every specialist toward the teacher's
# opposite class.  A specialist "votes against teacher" when its hard label
# differs from teacher.
# -------------------------------------------------------------------------
hard_o = (p_oof >= 0.5).astype(int)
hard_v = (p_val >= 0.5).astype(int)

disagree_o = hard_o != teacher_oof[:, None]
disagree_v = hard_v != teacher_val[:, None]

# Confidence that the specialist supports its hard prediction.
conf_o = np.maximum(p_oof, 1.0 - p_oof)
conf_v = np.maximum(p_val, 1.0 - p_val)

# Signed margin in direction "against teacher".
# Positive = specialist supports flipping teacher.
signed_o = np.where(
    hard_o != teacher_oof[:, None],
    conf_o - 0.5,
    -(conf_o - 0.5),
)
signed_v = np.where(
    hard_v != teacher_val[:, None],
    conf_v - 0.5,
    -(conf_v - 0.5),
)

vote_o = disagree_o.sum(axis=1)
vote_v = disagree_v.sum(axis=1)

# Average positive strength among specialists that disagree with teacher.
# Zero if nobody disagrees.
sum_dis_o = np.sum(np.where(disagree_o, conf_o - 0.5, 0.0), axis=1)
sum_dis_v = np.sum(np.where(disagree_v, conf_v - 0.5, 0.0), axis=1)

mean_dis_o = np.divide(
    sum_dis_o, vote_o, out=np.zeros_like(sum_dis_o), where=vote_o > 0
)
mean_dis_v = np.divide(
    sum_dis_v, vote_v, out=np.zeros_like(sum_dis_v), where=vote_v > 0
)

# Also require the weakest disagreeing specialist to have reasonable
# confidence.  This prevents one very weak vote from joining the consensus.
weak_dis_o = np.where(disagree_o, conf_o, 1.0).min(axis=1)
weak_dis_v = np.where(disagree_v, conf_v, 1.0).min(axis=1)

# -------------------------------------------------------------------------
# Rule search.
#
# Keep the rule family deliberately tiny and interpretable:
#
#   vote >= k
#   mean disagreement strength >= margin
#   weakest disagreeing confidence >= conf
#
# We search only OOF.  Among rules, prioritize safety:
#   1. positive OOF net gain
#   2. high precision of changes
#   3. small number of changes
#
# A rule must have >= 8 OOF changes to avoid selecting a rule on only 1–2
# lucky examples.
# -------------------------------------------------------------------------
rules = []

for k in [2, 3, 4, 5]:
    for margin in [0.05, 0.10, 0.15, 0.20, 0.25, 0.30]:
        for conf in [0.55, 0.60, 0.65, 0.70, 0.75, 0.80, 0.85, 0.90]:
            change = (
                (vote_o >= k)
                & (mean_dis_o >= margin)
                & (weak_dis_o >= conf)
            )

            n = int(change.sum())
            if n < 8:
                continue

            after = teacher_oof.copy()
            after[change] = 1 - after[change]

            acc = accuracy_score(y_oof, after)
            delta = acc - accuracy_score(y_oof, teacher_oof)

            correct = int(np.sum(after[change] == y_oof[change]))
            wrong = n - correct
            precision = correct / n if n else 0.0

            rules.append({
                "k": k,
                "margin": margin,
                "confidence": conf,
                "oof_changes": n,
                "oof_correct": correct,
                "oof_wrong": wrong,
                "oof_change_precision": precision,
                "oof_accuracy_after": float(acc),
                "oof_delta": float(delta),
            })

# Conservative ranking:
# require >= 65% change precision and positive OOF delta, then prefer fewer
# changes.  If no rule satisfies this, fall back to the highest precision
# rule with positive delta.
safe = [
    r for r in rules
    if r["oof_change_precision"] >= 0.65 and r["oof_delta"] > 0
]

if safe:
    # Maximize OOF delta first, but penalize changing many rows.
    # The penalty is intentionally tiny: we still want real improvement.
    selected = max(
        safe,
        key=lambda r: (r["oof_delta"] - 0.00002 * r["oof_changes"],
                       r["oof_change_precision"],
                       -r["oof_changes"])
    )
    selection_reason = "positive OOF delta + >=65% correction precision"
else:
    positive = [r for r in rules if r["oof_delta"] > 0]
    if positive:
        selected = max(
            positive,
            key=lambda r: (r["oof_change_precision"],
                           r["oof_delta"],
                           -r["oof_changes"])
        )
        selection_reason = "fallback: positive OOF delta"
    else:
        selected = {
            "k": 5,
            "margin": 0.30,
            "confidence": 0.90,
            "oof_changes": 0,
            "oof_correct": 0,
            "oof_wrong": 0,
            "oof_change_precision": 0.0,
            "oof_accuracy_after": float(accuracy_score(y_oof, teacher_oof)),
            "oof_delta": 0.0,
        }
        selection_reason = "no positive OOF rule; no correction"

k = selected["k"]
margin = selected["margin"]
conf = selected["confidence"]

change_o = (
    (vote_o >= k)
    & (mean_dis_o >= margin)
    & (weak_dis_o >= conf)
)
change_v = (
    (vote_v >= k)
    & (mean_dis_v >= margin)
    & (weak_dis_v >= conf)
)

corr_o = teacher_oof.copy()
corr_v = teacher_val.copy()
corr_o[change_o] = 1 - corr_o[change_o]
corr_v[change_v] = 1 - corr_v[change_v]

base_o = accuracy_score(y_oof, teacher_oof)
base_v = accuracy_score(y_val, teacher_val)
after_o = accuracy_score(y_oof, corr_o)
after_v = accuracy_score(y_val, corr_v)

o_correct = int(np.sum(corr_o[change_o] == y_oof[change_o]))
o_wrong = int(change_o.sum()) - o_correct

v_correct = int(np.sum(corr_v[change_v] == y_val[change_v]))
v_wrong = int(change_v.sum()) - v_correct

print("\n" + "=" * 78)
print("SELECTED CONSENSUS RULE")
print("=" * 78)
print(
    f"Require >= {k}/{M} specialists against teacher, "
    f"mean disagreement margin >= {margin:.2f}, "
    f"weakest confidence >= {conf:.2f}"
)
print(f"Selection: {selection_reason}")
print(
    f"OOF:  {base_o:.9f} -> {after_o:.9f} "
    f"delta={after_o-base_o:+.9f}, "
    f"changes={int(change_o.sum())}, "
    f"correct={o_correct}, wrong={o_wrong}"
)
print(
    f"VAL:  {base_v:.9f} -> {after_v:.9f} "
    f"delta={after_v-base_v:+.9f}, "
    f"changes={int(change_v.sum())}, "
    f"correct={v_correct}, wrong={v_wrong}"
)

# Show the actual validation cases touched by the frozen rule.
print("\nValidation changes:")
idx = np.where(change_v)[0]
for i in idx:
    print(
        f"  row={i:4d} teacher={teacher_val[i]} -> {corr_v[i]} "
        f"y={y_val[i]} votes={vote_v[i]} "
        f"mean_margin={mean_dis_v[i]:.3f} weak_conf={weak_dis_v[i]:.3f} "
        f"p=[" + ",".join(f"{x:.3f}" for x in p_val[i]) + "]"
    )

# Save enough artifacts to audit this experiment later.
np.savez(
    OUT_NPZ,
    y_oof=y_oof,
    y_val=y_val,
    teacher_oof=teacher_oof,
    teacher_val=teacher_val,
    specialist_names=np.array(names),
    specialist_p_oof=p_oof,
    specialist_p_val=p_val,
    change_oof=change_o,
    change_val=change_v,
    corrected_oof=corr_o,
    corrected_val=corr_v,
)

report = {
    "experiment": "Main115 strict cross-fitted specialist consensus correction",
    "n_splits": N_SPLITS,
    "feature_dim": int(X_oof.shape[1]),
    "teacher_oof_accuracy": float(base_o),
    "teacher_val_accuracy": float(base_v),
    "specialists": diag,
    "selected_rule": selected,
    "selection_reason": selection_reason,
    "selected_rule_frozen_validation": {
        "accuracy": float(after_v),
        "delta": float(after_v - base_v),
        "changes": int(change_v.sum()),
        "correct_changes": v_correct,
        "wrong_changes": v_wrong,
    },
    "selected_rule_oof": {
        "accuracy": float(after_o),
        "delta": float(after_o - base_o),
        "changes": int(change_o.sum()),
        "correct_changes": o_correct,
        "wrong_changes": o_wrong,
    },
    "note": (
        "Specialist probabilities on the 8428 Main64 OOF rows are "
        "5-fold cross-fitted. The consensus rule is selected only from "
        "those cross-fitted predictions and then frozen for validation."
    ),
}

with open(OUT_REPORT, "w") as f:
    json.dump(report, f, indent=2)

print(f"\nWrote: {OUT_REPORT.name}")
print(f"Wrote: {OUT_NPZ.name}")
print("=" * 78)
