"""
MAIN79
======

Final submission candidate:
    Main66 classical teacher
        +
    Main78-style neural residual ensemble

Important:
- The classical teacher used for the neural training targets is leakage-safe:
  Main64 OOF meta-features are used for the 8428 training rows and the
  held-out 2108 validation meta-features are used for the remaining rows.
- The test teacher is rebuilt from Main66's exact full-data classical pipeline.
- The residual branch is deliberately small and its final contribution is
  fixed at the conservative 0.025 weight validated in Main78.
- Three residual BiGRUs are trained and averaged, matching the useful
  Main78 ensemble idea.
- No validation score is invented here; this script's job is to produce
  submission_main79.csv.

Required files in this folder:
    train.json
    test.json
    main66.py
    main64_oof_meta_features.npy
    main64_val_meta_features.npy

Also required:
    main64_oof_svm.npy
    main64_oof_nbsvm.npy
    main64_oof_hgb.npy
    main64_oof_local.npy

The script does NOT modify train/test data.
"""

