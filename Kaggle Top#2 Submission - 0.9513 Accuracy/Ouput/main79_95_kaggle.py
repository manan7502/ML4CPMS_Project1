# SAFE MAIN64 META TEACHER
# ============================================================

def reconstruct_safe_teacher(texts, labels):
    """
    Main64 OOF meta features cover the 8428 training split.
    Main64 validation meta features cover the remaining 2108 rows.

    For every row, its stored base-model features were generated by a model
    that did not train on that row. We therefore have a leakage-safe teacher
    score for all 10536 labelled examples.
    """

    n = len(labels)

    idx = np.arange(n)

    train_idx, val_idx = train_test_split(
        idx,
        test_size=0.20,
        random_state=SEED,
        stratify=labels
    )

    oof_meta = np.load(OOF_META_FILE).astype(np.float32)
    val_meta = np.load(VAL_META_FILE).astype(np.float32)

    print("OOF meta:", oof_meta.shape)
    print("VAL meta:", val_meta.shape)

    if oof_meta.shape[0] != len(train_idx):
        raise RuntimeError(
            f"OOF meta has {oof_meta.shape[0]} rows, expected {len(train_idx)}."
        )

    if val_meta.shape[0] != len(val_idx):
        raise RuntimeError(
            f"VAL meta has {val_meta.shape[0]} rows, expected {len(val_idx)}."
        )

    if oof_meta.shape[1] != 13:
        raise RuntimeError(
            f"Expected 13 meta features, got {oof_meta.shape[1]}."
        )

    if val_meta.shape[1] != 13:
        raise RuntimeError(
            f"Expected 13 validation meta features, got {val_meta.shape[1]}."
        )

    # Exact Main66/Main78 meta learner.
    meta_model = LogisticRegression(
        C=META_C,
        max_iter=5000,
        solver="lbfgs",
        random_state=SEED
    )

    meta_model.fit(
        oof_meta,
        labels[train_idx]
    )

    teacher_train_raw = meta_model.decision_function(
        oof_meta
    ).astype(np.float32)

    teacher_val_raw = meta_model.decision_function(
        val_meta
    ).astype(np.float32)

    # Put both parts back into original dataset order.
    teacher_raw_all = np.empty(n, dtype=np.float32)
    teacher_raw_all[train_idx] = teacher_train_raw
    teacher_raw_all[val_idx] = teacher_val_raw

    # Same robust score scaling used by Main78.
    teacher_scale = np.percentile(
        np.abs(teacher_train_raw),
        95
    )

    if teacher_scale < 1e-6:
        teacher_scale = 1.0

    teacher_all = np.clip(
        teacher_raw_all / teacher_scale,
        -6.0,
        6.0
    ).astype(np.float32)

    # Same feature normalization convention used by Main78.
    meta_mean = np.mean(oof_meta, axis=0)
    meta_std = np.std(oof_meta, axis=0)
    meta_std = np.where(
        meta_std < 1e-6,
        1.0,
        meta_std
    )

    meta_all = np.empty_like(
        teacher_all[:, None],
        shape=(n, 13)
    )

    meta_all[train_idx] = np.clip(
        (oof_meta - meta_mean) / meta_std,
        -6.0,
        6.0
    )

    meta_all[val_idx] = np.clip(
        (val_meta - meta_mean) / meta_std,
        -6.0,
        6.0
    )

    # Useful sanity information.
    val_pred = (teacher_val_raw >= 0).astype(np.int64)
    val_acc = np.mean(val_pred == labels[val_idx])

    print(f"Reconstructed Main78 teacher validation accuracy: {val_acc:.6f}")
    print(f"Teacher raw scale: {teacher_scale:.6f}")
    print(
        "Teacher raw range:",
        float(teacher_raw_all.min()),
        float(teacher_raw_all.max())
    )

    return (
        train_idx,
        val_idx,
        meta_model,
        teacher_scale,
        meta_mean,
        meta_std,
        teacher_all,
        meta_all
    )


