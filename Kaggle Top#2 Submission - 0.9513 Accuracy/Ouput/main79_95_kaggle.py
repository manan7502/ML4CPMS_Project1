    print("Training final SVM...")
    test_svm = main66.train_svm(
        X_all_global,
        labels,
        X_test_global
    )

    print("Training final NB-SVM...")
    test_nbsvm = main66.train_nbsvm(
        all_strings,
        labels,
        test_strings
    )

    print("Training final HGB...")
    test_hgb = main66.train_hgb(
        X_all_compact,
        labels,
        X_test_compact
    )

    print("Computing final local geometry...")
    test_local = main66.local_geometry_features(
        X_all_tfidf,
        labels,
        X_test_tfidf,
        k=main66.LOCAL_K
    )

    # Exact Main66 meta scaler reconstructed from saved OOF raw scores.
    oof_svm = np.load(
        OOF_SVM_FILE
    ).reshape(-1)

    oof_nbsvm = np.load(
        OOF_NBSVM_FILE
    ).reshape(-1)

    oof_hgb = np.load(
        OOF_HGB_FILE
    ).reshape(-1)

    oof_local = np.load(
        OOF_LOCAL_FILE
    )

    if oof_local.ndim == 1:
        oof_local = oof_local[:, None]

    # Main66 convention: local features are A-positive, so invert.
    oof_local_b = -oof_local

