    # --------------------------------------------------------

    print("\n" + "=" * 72)
    print("STEP 3 — BUILD FULL-DATA MAIN66 TEST TEACHER")
    print("=" * 72)

    # main66.py contains the exact tested representation/base-model
    # implementation. Import it rather than reimplementing a subtly
    # different version here.
