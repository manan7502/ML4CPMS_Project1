@torch.no_grad()
def predict_residual(
    model,
    seqs,
    meta_z,
    teacher
):
    model.eval()

    dummy_labels = np.zeros(
        len(seqs),
        dtype=np.float32
    )

    ds = ResidualDataset(
        seqs,
        dummy_labels,
        meta_z
    )

    loader = DataLoader(
        ds,
        batch_size=BATCH_SIZE,
        shuffle=False,
        num_workers=NUM_WORKERS,
        pin_memory=(DEVICE.type == "cuda")
    )

    residuals = []

    for (
        ids,
        mask,
        _,
        aux
    ) in loader:
        ids = ids.to(
            DEVICE,
            non_blocking=True
        )

        mask = mask.to(
            DEVICE,
            non_blocking=True
        )

        aux = aux.to(
            DEVICE,
            non_blocking=True
        )

        with autocast_context():
            r = model(
                ids,
                mask,
                aux
            )

        residuals.append(
            r.float().cpu().numpy()
        )

    return np.concatenate(
        residuals
    ).astype(np.float32)


