# RESIDUAL DATASET
# ============================================================

class ResidualDataset(Dataset):
    def __init__(self, seqs, labels, meta_z):
        self.seqs = seqs
        self.labels = np.asarray(labels, dtype=np.float32)
        self.meta_z = np.asarray(meta_z, dtype=np.float32)

    def __len__(self):
        return len(self.seqs)

    def __getitem__(self, i):
        x = np.asarray(
            self.seqs[i],
            dtype=np.int64
        )

        if len(x) > MAX_LEN:
            x = x[:MAX_LEN]

        n = len(x)

        # Main78 convention:
        # PAD_IDX is one ID above the largest real token ID.
        ids = np.full(
            MAX_LEN,
            PAD_IDX,
            dtype=np.int64
        )

        mask = np.zeros(
            MAX_LEN,
            dtype=np.bool_
        )

        ids[:n] = x
        mask[:n] = True

        unique_ratio = (
            len(np.unique(x)) /
            max(n, 1)
        )

        repeat_ratio = 1.0 - unique_ratio
        length_log = np.log1p(n) / 7.0

        aux = np.concatenate([
            self.meta_z[i],
            np.asarray([
                unique_ratio,
                repeat_ratio,
                length_log
            ], dtype=np.float32)
        ]).astype(np.float32)

        return (
            torch.from_numpy(ids),
            torch.from_numpy(mask),
            torch.tensor(self.labels[i]),
            torch.from_numpy(aux)
        )


# ============================================================
# MODEL — MAIN78 ARCHITECTURE
# ============================================================

class ResidualBiGRU(nn.Module):
    def __init__(self, meta_dim):
        super().__init__()

        self.embedding = nn.Embedding(
            VOCAB_SIZE + 1,
            EMB_DIM,
            padding_idx=PAD_IDX
        )

        self.gru = nn.GRU(
            input_size=EMB_DIM,
            hidden_size=HIDDEN,
            num_layers=1,
            batch_first=True,
            bidirectional=True
        )

        enc_dim = 2 * HIDDEN
        pooled_dim = 3 * enc_dim

        self.attn = nn.Sequential(
            nn.Linear(enc_dim, 32),
            nn.Tanh(),
            nn.Linear(32, 1)
        )

        self.neural_proj = nn.Sequential(
            nn.Linear(pooled_dim, 64),
            nn.LayerNorm(64),
            nn.ReLU(),
            nn.Dropout(DROPOUT)
        )

        self.meta_proj = nn.Sequential(
            nn.Linear(meta_dim + 3, 32),
            nn.LayerNorm(32),
            nn.ReLU(),
            nn.Dropout(DROPOUT)
        )

        self.head = nn.Sequential(
            nn.Linear(96, 48),
            nn.ReLU(),
            nn.Dropout(DROPOUT),
            nn.Linear(48, 1)
        )

    def forward(self, ids, mask, aux):
        e = self.embedding(ids)

        h, _ = self.gru(e)

        mask_f = mask.unsqueeze(-1)

        denom = mask_f.sum(
            dim=1
        ).clamp_min(1)

        mean_pool = (
            h * mask_f
        ).sum(dim=1) / denom

        max_pool = h.masked_fill(
            ~mask_f,
            -1e4
        ).max(dim=1).values

        # Keep attention scores/pooling in FP32.
        # This avoids the FP16 overflow issue encountered in Main74.
        scores = self.attn(
            h.float()
        ).squeeze(-1)

        scores = scores.masked_fill(
            ~mask,
            -1e4
        )

        weights = torch.softmax(
            scores,
            dim=1
        )

        attn_pool = torch.sum(
            h.float() * weights.unsqueeze(-1),
            dim=1
        )

        pooled = torch.cat([
            mean_pool.float(),
            max_pool.float(),
            attn_pool
        ], dim=1)

        neural_z = self.neural_proj(
            pooled
        )

        meta_z = self.meta_proj(
            aux.float()
        )

        z = torch.cat([
            neural_z,
            meta_z
        ], dim=1)

        residual = self.head(
            z
        ).squeeze(-1)

        return residual


def autocast_context():
    if USE_AMP:
        return torch.autocast(
            device_type="cuda",
            dtype=torch.float16
        )

    return torch.autocast(
        device_type="cpu",
        enabled=False
    )


# ============================================================
# TRAIN ONE FULL-DATA RESIDUAL MODEL
# ============================================================

def train_one_seed(
    seed,
    train_loader,
    meta_dim
):
    print("\n" + "=" * 72)
    print(f"TRAINING MAIN79 RESIDUAL — SEED {seed}")
    print("=" * 72)

    seed_everything(seed)

    model = ResidualBiGRU(
        meta_dim
    ).to(DEVICE)

    print(
        "Parameters:",
        sum(
            p.numel()
            for p in model.parameters()
            if p.requires_grad
        )
    )

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=LR,
        weight_decay=WEIGHT_DECAY
    )

    criterion = nn.BCEWithLogitsLoss()

    scaler = torch.amp.GradScaler(
        "cuda",
        enabled=USE_AMP
    )

    # Main78 found 0.075 useful during training.
    # The final test-time residual is subsequently shrunk to 0.025.
    TRAIN_WEIGHT = 0.075

    for epoch in range(1, EPOCHS + 1):
        model.train()

        loss_sum = 0.0
        total = 0
        correct = 0

        t0 = time.time()

        for batch_i, (
            ids,
            mask,
            y,
            aux
        ) in enumerate(
            train_loader,
            1
        ):
            ids = ids.to(
                DEVICE,
                non_blocking=True
            )

            mask = mask.to(
                DEVICE,
                non_blocking=True
            )

            y = y.to(
                DEVICE,
                non_blocking=True
            )

            aux = aux.to(
                DEVICE,
                non_blocking=True
            )

            optimizer.zero_grad(
                set_to_none=True
            )

            with autocast_context():
                residual = model(
                    ids,
                    mask,
                    aux
                )

                # aux[:, 0] is the normalized classical teacher.
                teacher = aux[:, 0]

                final_logit = (
                    teacher +
                    TRAIN_WEIGHT * residual
                )

                loss = criterion(
                    final_logit,
                    y
                )

            if not torch.isfinite(loss):
                print(
                    "WARNING: non-finite loss; skipping batch"
                )
                continue

            scaler.scale(
                loss
            ).backward()

            scaler.unscale_(
                optimizer
            )

            torch.nn.utils.clip_grad_norm_(
                model.parameters(),
                GRAD_CLIP
            )

            scaler.step(
                optimizer
            )

            scaler.update()

            pred = (
                final_logit.detach() >= 0
            ).long()

            correct += int(
                (pred == y.long()).sum().item()
            )

            total += len(y)

            loss_sum += (
                float(loss.item()) *
                len(y)
            )

        train_acc = (
            correct /
            max(total, 1)
        )

        avg_loss = (
            loss_sum /
            max(total, 1)
        )

        print(
            f"epoch {epoch:02d}/{EPOCHS} | "
            f"train_acc={train_acc:.5f} | "
            f"loss={avg_loss:.5f} | "
            f"time={(time.time()-t0)/60:.2f} min"
        )

    path = OUT_DIR / f"main79_residual_seed{seed}.pt"

    torch.save(
        model.state_dict(),
        path
    )

    print("Saved:", path)

    return model


