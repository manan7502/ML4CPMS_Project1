    # Main115 alignment.
    # ------------------------------------------------------------------
    m115 = np.load(MAIN115_RESULTS, allow_pickle=True)

    y_oof_115 = np.asarray(m115["y_oof"]).astype(np.int64)
    y_val_115 = np.asarray(m115["y_val"]).astype(np.int64)

    if len(y_oof_115) != len(tr_idx):
        raise RuntimeError("Main115 OOF length does not match canonical train.")
    if len(y_val_115) != len(va_idx):
        raise RuntimeError("Main115 VAL length does not match canonical val.")

    if not np.array_equal(y_oof_115, y[tr_idx]):
        raise RuntimeError("Main115 OOF label alignment failed.")
    if not np.array_equal(y_val_115, y[va_idx]):
        raise RuntimeError("Main115 VAL label alignment failed.")

    specialist_oof = np.asarray(
        m115["specialist_p_oof"], dtype=np.float32
    )
    specialist_val = np.asarray(
        m115["specialist_p_val"], dtype=np.float32
    )

    print("Main115 OOF alignment: PASS")
    print("Main115 VAL alignment: PASS")

    # ------------------------------------------------------------------
    # Exact Main131 validation reconstruction safety check.
    # ------------------------------------------------------------------
    checkpoint = torch.load(
        MAIN131_CHECKPOINT,
        map_location="cpu",
        weights_only=False,
    )

    saved = np.load(MAIN131_EMBEDDINGS, allow_pickle=True)
    saved_va_idx = np.asarray(saved["val_indices"]).astype(np.int64)
    saved_z_val = np.asarray(saved["z_val"]).astype(np.float32)

    if not np.array_equal(saved_va_idx, va_idx):
        raise RuntimeError(
            "FAIL: saved Main131 validation indices do not match canonical "
            "validation order."
        )

    print("\nReconstructing exact Main131 validation latent...")
    z_val_exact = reconstruct_exact_main131_validation(
        token_lists,
        va_idx,
        checkpoint,
        main131,
    )

    max_diff = float(np.max(np.abs(z_val_exact - saved_z_val)))
    mean_diff = float(np.mean(np.abs(z_val_exact - saved_z_val)))

    print("Main131 z_val max abs diff :", max_diff)
    print("Main131 z_val mean abs diff:", mean_diff)
    print("Safety tolerance           :", TOL)

    if max_diff >= TOL:
        raise RuntimeError(
            "FAIL: Main131 validation reconstruction exceeds 1e-5. "
            "Do not continue to fusion."
        )

    print("Main131 validation reconstruction: PASS")

    # ------------------------------------------------------------------
    # Strict 5-fold OOF Main131 representation.
    # ------------------------------------------------------------------
    print("\nStarting strict 5-fold Main131 OOF generation...")

    skf = StratifiedKFold(
        n_splits=N_SPLITS,
        shuffle=True,
        random_state=SEED,
    )

    z_oof = np.zeros(
        (len(tr_idx), LATENT_DIM),
        dtype=np.float32,
    )

