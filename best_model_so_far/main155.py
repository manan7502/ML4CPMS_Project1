"""
MAIN155 / EXPERIMENT 35
STRICT OOF MAIN131 + MAIN115 FUSION

Purpose
-------
Test whether the Main131 / Exp11 learned representation adds useful
information to the Main115 specialist probabilities under a strict,
leakage-safe fusion protocol.

Main131 is the actual Exp11 architecture:
    word TF-IDF (1-3 grams, 60k features)
        -> Linear(60000, 128) + BN/GELU/Dropout
    structural 62-D features
        -> Linear(62, 128) + BN/GELU/Dropout
    concat 256
        -> Linear(256, 192) + BN/GELU/Dropout
        -> Linear(192, 128) + BN/GELU/Dropout
        -> classifier

Strict OOF protocol:
    - canonical 8428/2108 split is preserved exactly
    - Main115 OOF/VAL probabilities are used as fixed inputs
    - Main131 representation is generated by 5-fold cross-fitting
    - each fold fits TF-IDF and structural scaler only on fold-train
    - each fold trains Main131 for exactly 3 epochs
    - held-out rows are never used to fit that fold's representation
    - validation uses the saved Main131 checkpoint and is never used to
      train/tune the fusion classifier
    - LR and LinearSVC are trained only on the 8428-row strict OOF matrix

No validation tuning.
No Kaggle submission.
"""

