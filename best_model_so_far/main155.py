    print(f"OOF accuracy: {lr_oof_acc}")
    print(f"OOF AUC     : {lr_oof_auc}")
    print(f"VAL accuracy: {lr_val_acc}")
    print(f"VAL AUC     : {lr_val_auc}")

    svm_fusion = LinearSVC(
        C=1.0,
        class_weight="balanced",
        random_state=SEED,
    )
    svm_fusion.fit(X_fusion_oof, y_oof_115)

    svm_oof_score = svm_fusion.decision_function(X_fusion_oof)
    svm_val_score = svm_fusion.decision_function(X_fusion_val)

    svm_oof_pred = (svm_oof_score >= 0.0).astype(np.int64)
    svm_val_pred = (svm_val_score >= 0.0).astype(np.int64)

    svm_oof_acc = accuracy_score(y_oof_115, svm_oof_pred)
    svm_val_acc = accuracy_score(y_val_115, svm_val_pred)
    svm_oof_auc = roc_auc_score(y_oof_115, svm_oof_score)
    svm_val_auc = roc_auc_score(y_val_115, svm_val_score)

    print("\n=== STRICT OOF LINEAR SVM FUSION ===")
    print(f"OOF accuracy: {svm_oof_acc}")
    print(f"OOF AUC     : {svm_oof_auc}")
    print(f"VAL accuracy: {svm_val_acc}")
    print(f"VAL AUC     : {svm_val_auc}")

